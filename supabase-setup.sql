create table if not exists public.lyrics_verified (
    id bigint generated by default as identity primary key,
    titulo text not null,
    artista text not null default '',
    titulo_norm text not null default '',
    artista_norm text not null default '',
    plain_lyrics text,
    synced_lyrics text,
    fonte text not null default 'manual',
    observacao text,
    ativo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.lyrics_verified
    add column if not exists titulo text,
    add column if not exists artista text default '',
    add column if not exists titulo_norm text default '',
    add column if not exists artista_norm text default '',
    add column if not exists plain_lyrics text,
    add column if not exists synced_lyrics text,
    add column if not exists fonte text default 'manual',
    add column if not exists observacao text,
    add column if not exists ativo boolean default true,
    add column if not exists created_at timestamptz default now(),
    add column if not exists updated_at timestamptz default now();

update public.lyrics_verified
set artista = ''
where artista is null;

update public.lyrics_verified
set titulo_norm = lower(trim(titulo))
where titulo_norm is null or titulo_norm = '';

update public.lyrics_verified
set artista_norm = lower(trim(artista))
